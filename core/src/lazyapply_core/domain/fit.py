"""FitReport: the output of the evaluation engine, and the Phase 2 gate.

Division of labour, which is the core design idea of this system:

- Retrieval decides **candidacy** — what evidence exists at all.
- The model decides **sufficiency** — whether that evidence satisfies the
  requirement. It emits STRONG / PARTIAL / NONE per requirement, nothing more.
- Code decides the **verdict** — a pure function over those statuses.

The model is never asked for the verdict. That keeps the decision reproducible,
unit-testable without an API key, tunable against the golden set, and
explainable to a user ("you are missing 3 of 7 must-haves").
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field

from lazyapply_core.domain.evidence import EvidenceId


class MatchStatus(StrEnum):
    STRONG = "strong"
    PARTIAL = "partial"
    NONE = "none"


class Verdict(StrEnum):
    GENERATE = "generate"
    """Fit is good. Phase 2's CV agent runs only on this."""

    BORDERLINE = "borderline"
    """Real gaps, but arguable. Surfaced to the user to decide."""

    SKIP = "skip"
    """Not a fit. No CV is generated; the gap list is returned instead."""


class RequirementMatch(BaseModel):
    """The model's judgment on one requirement, with its citations."""

    model_config = ConfigDict(frozen=True)

    requirement_id: str
    status: MatchStatus

    evidence_ids: tuple[EvidenceId, ...] = ()
    """Must all appear in the pack that was sent to the model. Enforced by the
    citation verifier — a citation to anything else is a hard failure, not a
    warning."""

    best_retrieval_score: float | None = None
    """Diagnostic for threshold tuning. Never an input to the verdict."""

    rationale: str
    """One sentence. Shown to the user, not parsed."""


class FitReport(BaseModel):
    model_config = ConfigDict(frozen=True)

    role_id: str
    profile_version: str
    created_at: datetime

    matches: tuple[RequirementMatch, ...]

    must_have_coverage: float = Field(ge=0.0, le=1.0)
    """(strong + 0.5 * partial) / total must-haves."""

    score: int = Field(ge=0, le=100)
    verdict: Verdict

    gaps: tuple[str, ...] = ()
    """Requirement ids with status NONE. Derived from ``matches``, never
    generated by the model."""
